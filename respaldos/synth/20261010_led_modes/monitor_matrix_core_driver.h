static Arduino_LED_Matrix matrix;
static uint8_t active = 0;
inline bool decode(const uint8_t *p, size_t size, uint8_t &mode) {
    if (size != scope_control::BLOCK || memcmp(p,"SCP1",4) || p[4]!=4 || p[5] ||
        p[6]!=14 || p[7] || scope_control::get32(p+12)!=972 ||
        !scope_control::pc_id(scope_control::get32(p+8)) ||
        scope_control::get32(p+988)!=scope_control::crc(p,988) || p[16]>10) return false;
    for (unsigned i=17;i<988;++i) if(p[i]) return false;
    mode=p[16]; return true;
}
inline void show(uint8_t mode) {
    if(mode==active || mode>10) return;
    if(!mode) { matrix.clear(); matrix.end(); }
    else {
        if(!active) { matrix.begin(); matrix.setGrayscaleBits(3); }
        matrix.draw(icons[mode]);
    }
    active=mode;
}
